import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');

function esc(str) {
  return `'${String(str).replace(/'/g, "''")}'`;
}

function readConstStringArray(filePath, constName) {
  const src = fs.readFileSync(filePath, 'utf8');
  const re = new RegExp(`export const ${constName}\\s*=\\s*\\[([\\s\\S]*?)\\]`, 'm');
  const match = src.match(re);
  if (!match) throw new Error(`Could not find ${constName} in ${filePath}`);
  return [...match[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

function readSetStrings(src, constName) {
  const re = new RegExp(`const ${constName}\\s*=\\s*new Set[^(]*\\(\\[([\\s\\S]*?)\\]\\)`, 'm');
  const match = src.match(re);
  if (!match) throw new Error(`Could not find ${constName}`);
  return new Set([...match[1].matchAll(/'([^']+)'/g)].map((m) => m[1]));
}

// 1. Objects
const objectsSrc = fs.readFileSync(path.join(projectRoot, 'src/content/objects.ts'), 'utf8');
const countableSet = readSetStrings(objectsSrc, 'COUNTABLE_SET');
const cardFaceSet = readSetStrings(objectsSrc, 'CARD_FACE_SET');
const mazeGoalSet = readSetStrings(objectsSrc, 'MAZE_GOAL_SET');

const rawNamesMatch = objectsSrc.match(/const RAW_NAMES[^=]*=\s*\{([\s\S]*?)\n\};/m);
if (!rawNamesMatch) throw new Error('Could not find RAW_NAMES');
const objectRows = [];
for (const m of rawNamesMatch[1].matchAll(
  /(?:'([^']+)'|([a-z0-9-]+))\s*:\s*\{\s*id:\s*'([^']+)',\s*en:\s*'([^']+)'\s*\}/g,
)) {
  const id = m[1] || m[2];
  objectRows.push({
    id,
    name_id: m[3],
    name_en: m[4],
    countable: countableSet.has(id),
    card_face: cardFaceSet.has(id),
    maze_goal: mazeGoalSet.has(id),
  });
}

// 2. Words
const wordsSrc = fs.readFileSync(path.join(projectRoot, 'src/content/words.ts'), 'utf8');
const wordRows = [];
for (const m of wordsSrc.matchAll(
  /\{\s*locale:\s*'(id|en)',\s*word:\s*'([A-Z]+)',\s*objectId:\s*'([a-z0-9-]+)',\s*initial:\s*(true|false),\s*spell:\s*(true|false)\s*\}/g,
)) {
  wordRows.push({
    locale: m[1],
    word: m[2],
    object_id: m[3],
    use_initial: m[4] === 'true',
    use_spell: m[5] === 'true',
  });
}

// 3. Hijaiyyah
const hijaSrc = fs.readFileSync(path.join(projectRoot, 'src/content/hijaiyyah.ts'), 'utf8');
const hijaRows = [];
for (const m of hijaSrc.matchAll(
  /\{\s*id:\s*'([^']+)',\s*char:\s*'([^']+)',\s*nameId:\s*(?:'([^']+)'|"([^"]+)"),\s*family:\s*'([^']+)',\s*traceGroup:\s*'(mudah|sedang|tantang)'\s*\}/g,
)) {
  hijaRows.push({
    id: m[1],
    char: m[2],
    name_id: m[3] || m[4],
    family: m[5],
    trace_group: m[6],
  });
}

// 4. Speech clips (21*2 num + 26*2 letter = 94)
const speechRows = [];
for (const locale of ['id', 'en']) {
  for (let n = 0; n <= 20; n++) {
    speechRows.push({ kind: 'num', locale, key: String(n) });
  }
  for (let i = 0; i < 26; i++) {
    speechRows.push({ kind: 'letter', locale, key: String.fromCharCode(97 + i) });
  }
}

// 5. Scene audio (6 music + 4 ambient + 17 sfx = 27)
const audioTypesPath = path.join(projectRoot, 'src/lib/audio/types.ts');
const musicIds = readConstStringArray(audioTypesPath, 'MUSIC_IDS');
const ambientIds = readConstStringArray(audioTypesPath, 'AMBIENT_IDS');
const sfxIds = readConstStringArray(audioTypesPath, 'SFX_IDS');
const sceneRows = [
  ...musicIds.map((id) => ({ id: `music:${id}`, layer: 'music' })),
  ...ambientIds.map((id) => ({ id: `ambient:${id}`, layer: 'ambient' })),
  ...sfxIds.map((id) => ({ id: `sfx:${id}`, layer: 'sfx' })),
];

const lines = [
  '-- Generated by scripts/gen-cms-seed.mjs — idempotent seed for CMS tables',
  '',
  'insert into public.objects (id, name_id, name_en, countable, card_face, maze_goal) values',
  objectRows
    .map(
      (o) =>
        `  (${esc(o.id)}, ${esc(o.name_id)}, ${esc(o.name_en)}, ${o.countable}, ${o.card_face}, ${o.maze_goal})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
  '',
  'insert into public.words (locale, word, object_id, use_initial, use_spell) values',
  wordRows
    .map(
      (w) =>
        `  (${esc(w.locale)}, ${esc(w.word)}, ${esc(w.object_id)}, ${w.use_initial}, ${w.use_spell})`,
    )
    .join(',\n') + '\non conflict (locale, word) do nothing;',
  '',
  'insert into public.hijaiyyah (id, char, name_id, family, trace_group) values',
  hijaRows
    .map(
      (h) =>
        `  (${esc(h.id)}, ${esc(h.char)}, ${esc(h.name_id)}, ${esc(h.family)}, ${esc(h.trace_group)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
  '',
  'insert into public.speech_clips (kind, locale, key) values',
  speechRows
    .map((s) => `  (${esc(s.kind)}, ${esc(s.locale)}, ${esc(s.key)})`)
    .join(',\n') + '\non conflict (kind, locale, key) do nothing;',
  '',
  'insert into public.scene_audio (id, layer) values',
  sceneRows.map((s) => `  (${esc(s.id)}, ${esc(s.layer)})`).join(',\n') +
    '\non conflict (id) do nothing;',
  '',
];

const outPath = path.join(projectRoot, 'supabase/migrations/0002_seed.sql');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log('Generated supabase/migrations/0002_seed.sql:');
console.log(`  objects:      ${objectRows.length}`);
console.log(`  words:        ${wordRows.length}`);
console.log(`  hijaiyyah:    ${hijaRows.length}`);
console.log(`  speech_clips: ${speechRows.length}`);
console.log(`  scene_audio:  ${sceneRows.length}`);
